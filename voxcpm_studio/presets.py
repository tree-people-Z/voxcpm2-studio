def compose(selected: dict[str, str], order: list[str]) -> str:
    """按维度顺序把已选标签拼成一句描述（未选的维度跳过）。"""
    parts = [selected[k] for k in order if selected.get(k)]
    return "，".join(parts)


def flat(groups: dict[str, list[str]]) -> list[str]:
    return [tag for tags in groups.values() for tag in tags]
